// Run after replacing character artwork. Uses the same palette algorithm as the UI.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'assets/js/lobby-theme.js'), 'utf8');
const context = { document: { getElementById: () => ({classList: {contains: () => true}}), documentElement: {} }, Map, Set };
vm.runInNewContext(source.slice(0, source.indexOf('    function update()')) + '\n globalThis.extractPalette = palette; })();', context);
(async () => {
    const palettes = {};
    for (const file of fs.readdirSync(path.join(root, 'assets/character-art')).filter(name => name.endsWith('.webp')).sort()) {
        const pixels = await sharp(path.join(root, 'assets/character-art', file)).resize(48, 48, {fit: 'fill'}).ensureAlpha().raw().toBuffer();
        const colors = context.extractPalette(pixels);
        if (colors) palettes[path.parse(file).name] = colors;
    }
    fs.writeFileSync(path.join(root, 'assets/js/lobby-palettes.js'), '// Generated by scripts/generate-lobby-palettes.cjs from character artwork.\n' +
        'globalThis.LobbyPalettes = ' + JSON.stringify(palettes, null, 2) + ';\n');
    console.log(`Generated ${Object.keys(palettes).length} character palettes.`);
})().catch(error => { console.error(error); process.exitCode = 1; });

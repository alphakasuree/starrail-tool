export function validateMessages(value) {
    if (!value || !Array.isArray(value.messages) || value.messages.length < 1 || value.messages.length > 21) return null;
    let total = 0;
    const messages = [];
    for (const [i, item] of value.messages.entries()) {
        if (!item || item.role !== (i % 2 === 0 ? 'user' : 'assistant') || typeof item.content !== 'string' || !item.content.trim() || item.content.length > 4000) return null;
        total += item.content.length;
        messages.push({role:item.role, content:item.content.trim()});
    }
    if (messages.at(-1).role !== 'user' || total > 24000) return null;
    return messages;
}
